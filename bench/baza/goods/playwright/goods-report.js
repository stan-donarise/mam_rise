const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium, resultScenario, resultStep, resultBenchmark, screenshot } = require('../../../playwright/harness')
resultScenario({ title: 'HTML-отчёт бенчмарка', group: 'entities' })

async function main() {
	const browser = await chromium.launch({ headless: true })
	try {
		const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
		const errors = []
		page.on('pageerror', error=>errors.push(error.message))
		resultStep('Открыть отчёт и сравнение схем', [])
		await resultBenchmark('Открыть HTML-отчёт', async()=> {
			await page.goto('http://localhost:9080/rise/bench/baza/goods/report/goods.benchmark.html')
			await page.locator('#shard-table tbody tr').last().waitFor()
		})
		assert.equal(await page.locator('#shard-table tbody tr').count(),20)
		assert.equal(await page.locator('#shard-comparison tbody tr').count(),8)
		assert.equal(await page.locator('#table tbody tr').count(),40)
		assert.equal(await page.locator('#table table').count(),2)
		assert.equal(await page.locator('.table-wrap th').evaluateAll(headers=>headers.some(header=>header.textContent.includes('Фриз F5'))),false)
		assert.equal(await page.locator('#table-compact thead th').count(),8)
		assert.equal(await page.locator('#table-full thead th').count(),8)
		assert.equal(await page.locator('#table-compact thead th').evaluateAll(headers=>headers.filter(header=>header.textContent==='F5, с').length),1)
		assert.equal(await page.locator('#table tbody tr.group-start').count(),6)
		for(const schema of ['compact','full']) {
			assert.equal(await page.locator('#table-'+schema+' table').evaluate(table=>table.getBoundingClientRect().width),760)
			assert.equal(await page.locator('#table-'+schema+' tbody tr').count(),20)
			const groups = await page.locator('#table-'+schema+' tbody tr').evaluateAll(rows=>rows.filter((row,index)=>index===0||row.classList.contains('group-start')).map(row=>row.cells[0].textContent))
			assert.deepEqual(groups,['Land','Area','Шарды 64','Шарды 256'])
		}
		assert.equal(await page.locator('.table-wrap tbody td').evaluateAll(cells=>cells.some(cell=>cell.scrollWidth>cell.clientWidth)),false)
		assert.equal(await page.locator('#table tbody tr').evaluateAll(rows=>rows.some(row=>row.getBoundingClientRect().height>34)),false)
		assert.equal(await page.locator('h1').textContent(),'Giper Baza: результаты бенчмарка')
		assert.equal(await page.locator('body').evaluate(body=>/Где баланс\?|Отдельное приложение со штатным/.test(body.innerText)),false)
		assert.equal(await page.locator('svg').count(),13)
		assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
		await screenshot(page,'report-desktop.png')
		await page.locator('#table').evaluate(element=>element.scrollIntoView({block:'start'}))
		await screenshot(page,'all-metrics.png',{fullPage:false})
		await page.setViewportSize({width:1800,height:1000})
		const tables = await page.locator('#table .table-wrap').evaluateAll(elements=>elements.map(element=>({top:element.getBoundingClientRect().top,left:element.getBoundingClientRect().left})))
		assert.equal(tables[0].top,tables[1].top)
		assert(tables[1].left>tables[0].left)
		assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
		await page.locator('#table').evaluate(element=>element.scrollIntoView({block:'start'}))
		await screenshot(page,'all-metrics-side-by-side.png',{fullPage:false})
		await page.setViewportSize({width:1440,height:1000})
		await page.locator('#shard-comparison').evaluate(element=>element.scrollIntoView({block:'start'}))
		await screenshot(page,'shards-comparison.png',{fullPage:false})

		resultStep('Переключить шкалу и скачать CSV', [])
		await resultBenchmark('Переключить логарифмическую шкалу', ()=>page.selectOption('#scale','log'))
		assert.equal(await page.evaluate(()=>Array.from(document.querySelectorAll('svg')).some(svg=>/NaN|Infinity/.test(svg.innerHTML))),false)
		const downloaded=page.waitForEvent('download')
		await page.locator('#csv').click()
		const download=await downloaded
		const csv=fs.readFileSync(await download.path(),'utf8')
		assert.equal(csv.trim().split(/\r?\n/).length,47)
		assert(csv.includes('coldfreeze_seconds'))
		assert(csv.includes('shard64'))
		assert(csv.includes('shard256'))

		resultStep('Проверить узкое окно', [])
		await page.setViewportSize({width:390,height:844})
		assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
		await page.evaluate(()=>window.scrollTo(0,0))
		await screenshot(page,'report-mobile.png',{fullPage:false})
		assert.deepEqual(errors,[])
	} finally {
		await browser.close()
	}
}
main().catch(error=>{console.error(error);process.exitCode=1})
